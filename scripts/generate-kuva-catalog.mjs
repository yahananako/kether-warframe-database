import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "data", "kuvaWeapons.generated.ts");
const UPDATED_AT = new Date().toISOString().slice(0, 10);

const ENDPOINTS = {
  items: "https://api.warframestat.us/items",
  dictionary: "https://browse.wf/warframe-public-export-plus/dict.tc.json",
  weapons: "https://browse.wf/warframe-public-export-plus/ExportWeapons.json",
};

const categoryMap = {
  Primary: { category: "primary", section: "赤毒主要武器", weaponType: "主要武器" },
  Secondary: { category: "secondary", section: "赤毒次要武器", weaponType: "次要武器" },
  Melee: { category: "melee", section: "赤毒近戰武器", weaponType: "近戰武器" },
  "Arch-Gun": { category: "archwing", section: "赤毒曲翼槍", weaponType: "曲翼武器" },
};

async function fetchJson(url) {
  const response = await fetch(url, {
    headers: {
      Accept: "application/json",
      "User-Agent": "KETHER-kuva-catalog/1.0",
    },
  });

  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}: ${url}`);
  }

  return response.json();
}

function cleanText(value) {
  return String(value || "")
    .replace(/^（英文：[\s\S]*?）\s*/u, "")
    .replace(/^\(English:[\s\S]*?\)\s*/iu, "")
    .replace(/<[^>]+>/gu, "")
    .replace(/\s+/gu, " ")
    .trim();
}

function marketSlug(value) {
  return String(value || "")
    .trim()
    .replace(/[’']/gu, "")
    .replace(/[^A-Za-z0-9]+/gu, "_")
    .replace(/^_+|_+$/gu, "")
    .toLowerCase();
}

function makeAliases(item, chineseName) {
  const englishBase = item.name.replace(/^Kuva\s+/iu, "");
  const chineseBase = chineseName.replace(/^赤毒\s*/u, "");

  return Array.from(new Set([
    item.name,
    item.name.replace(/\s+/gu, ""),
    chineseName,
    chineseName.replace(/\s+/gu, ""),
    englishBase,
    chineseBase,
    `赤毒${chineseBase}`,
    item.type,
    "Kuva",
    "赤毒",
    "赤毒武器",
    "赤毒玄骸",
  ].filter(Boolean)));
}

const [items, dictionary, weaponExport] = await Promise.all([
  fetchJson(ENDPOINTS.items),
  fetchJson(ENDPOINTS.dictionary),
  fetchJson(ENDPOINTS.weapons),
]);

const kuvaWeapons = items
  .filter((item) => {
    return item.masterable &&
      /^Kuva /iu.test(item.name) &&
      categoryMap[item.category] &&
      (!item.releaseDate || item.releaseDate <= UPDATED_AT);
  })
  .map((item) => {
    const category = categoryMap[item.category];
    const exportEntry = weaponExport[item.uniqueName] || {};
    const chineseName = cleanText(dictionary[exportEntry.name]) || item.name;
    const description = cleanText(dictionary[exportEntry.description]) || cleanText(item.description) || "赤毒玄骸武器。";
    const slug = marketSlug(item.name);
    const marketUrl = `https://warframe.market/auctions/search?type=lich&weapon_url_name=${slug}`;

    return {
      category: category.category,
      section: category.section,
      chineseName,
      englishName: item.name,
      description,
      priority: "待評估",
      price: "玄骸拍賣浮動",
      tradeText: "查看玄骸拍賣",
      owned: "未購買",
      source: "擊敗持有該武器的 Kuva Lich／赤毒玄骸後選擇「擊殺」領取；若要交易玄骸，結算時必須選擇「轉化」。",
      note: `武器本體不可交易；可在氏族緋紅支部交易一次已轉化玄骸。拍賣價受元素、加成％與幻紋影響。MR ${item.masteryReq ?? "—"}｜推出 ${item.releaseDate || "日期未收錄"}`,
      marketUrl,
      marketKind: "lich",
      marketSlug: slug,
      marketName: `${item.name} 赤毒玄骸`,
      tradeNote: "交易的是已轉化赤毒玄骸，不是已領取的武器本體；價格會隨元素、加成％與幻紋浮動。",
      imageUrl: item.imageName ? `https://cdn.warframestat.us/img/${item.imageName}` : "",
      aliases: makeAliases(item, chineseName),
      weaponType: category.weaponType,
      weaponTypeKey: category.category,
      series: "赤毒",
      seriesKey: "kuva",
      parts: "不需一般藍圖或部件；完成安魂密語、赤毒玄骸對決與銳捷號最終戰後取得。",
      tips: "刷幼體前先確認頭頂顯示的是目標武器；元素種類由擊倒幼體時使用的戰甲決定。",
      notes: `MR ${item.masteryReq ?? "—"}｜推出 ${item.releaseDate || "日期未收錄"}｜武器本體不可交易。`,
    };
  })
  .sort((left, right) => {
    const categoryOrder = ["primary", "secondary", "melee", "archwing"];
    const categoryDiff = categoryOrder.indexOf(left.category) - categoryOrder.indexOf(right.category);
    return categoryDiff || left.englishName.localeCompare(right.englishName);
  });

if (kuvaWeapons.length === 0) {
  throw new Error("Warframe 公開資料沒有回傳赤毒武器，已停止覆寫輸出。");
}

const content = `// Generated by scripts/generate-kuva-catalog.mjs.\n// Sources: Warframe Public Export and WarframeStat.\n\nexport type KuvaWeaponCatalogRow = {\n  category: \"primary\" | \"secondary\" | \"melee\" | \"archwing\";\n  section: string;\n  chineseName: string;\n  englishName: string;\n  description: string;\n  priority: string;\n  price: string;\n  tradeText: string;\n  owned: string;\n  source: string;\n  note: string;\n  marketUrl: string;\n  marketKind: \"lich\";\n  marketSlug: string;\n  marketName: string;\n  tradeNote: string;\n  imageUrl: string;\n  aliases: string[];\n  weaponType: string;\n  weaponTypeKey: string;\n  series: \"赤毒\";\n  seriesKey: \"kuva\";\n  parts: string;\n  tips: string;\n  notes: string;\n};\n\nexport const KUVA_WEAPONS_UPDATED_AT = ${JSON.stringify(UPDATED_AT)};\n\nexport const KUVA_WEAPONS: KuvaWeaponCatalogRow[] = ${JSON.stringify(kuvaWeapons, null, 2)};\n`;

await writeFile(OUTPUT, content, "utf8");

const counts = kuvaWeapons.reduce((map, item) => {
  map[item.category] = (map[item.category] || 0) + 1;
  return map;
}, {});

console.log(JSON.stringify({
  output: OUTPUT,
  updatedAt: UPDATED_AT,
  counts,
  total: kuvaWeapons.length,
}, null, 2));
